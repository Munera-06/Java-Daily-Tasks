/* Question: Perform Arithmetic Operations in Java
Write a Java program to declare two integer variables a = 30 and b = 5, and perform the following arithmetic operations:
	
Addition

Subtraction

Multiplication

Division

Modulus (Remainder)*/

package Package1;

public class Day1 {

	public static void main(String[] args) {
		int a=30;
		int b=5;
		int c=a+b;
		int d=a-b;
		int e=a*b;
		int f=a/b;
		int g=a%b;
		System.out.println(c);
		System.out.println(d);
		System.out.println(e);
		System.out.println(f);
		System.out.println(g);
	}

}
