/*Question:

Write a Java program to print all even numbers from 0 to 50 using a for loop.

Initialize the variable i with 0, check the condition i <= 50, and increment the value of i by 2 in each iteration. Display all even numbers from 0 to 50 on separate lines.*/

package Package1;

public class Day5_Task4 {

	public static void main(String[] args) {
		for(int i=0; i<=50; i+=2) //
		{
			System.out.println(i);
		}

	}

}
